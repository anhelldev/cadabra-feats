create policy "ver torneos publicados" on public.torneos for select to anon, authenticated
  using (estado <> 'borrador' or public.es_admin());
create policy "admin crea torneos" on public.torneos for insert to authenticated with check (public.es_admin());
create policy "admin edita torneos" on public.torneos for update to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy "admin borra torneos" on public.torneos for delete to authenticated using (public.es_admin());

-- Los datos personales de las inscripciones son solo del admin; el público ve nombres a través de las vistas de abajo.
create policy "cualquiera se inscribe" on public.inscripciones for insert to anon, authenticated
  with check (acepta and exists (select 1 from public.torneos t where t.id = torneo_id and t.estado = 'inscripcion'));
create policy "admin ve inscripciones" on public.inscripciones for select to authenticated using (public.es_admin());
create policy "admin edita inscripciones" on public.inscripciones for update to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy "admin borra inscripciones" on public.inscripciones for delete to authenticated using (public.es_admin());

create policy "admin gestiona partidas" on public.partidas for all to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy "admin gestiona jugadores de partida" on public.partida_jugadores for all to authenticated
  using (public.es_admin()) with check (public.es_admin());

-- Vistas públicas: solo nombres, sin teléfono ni correo, y solo de torneos publicados.
create view public.torneo_participantes with (security_invoker = false) as
  select i.id, i.torneo_id, i.nombre, i.estado
  from public.inscripciones i
  join public.torneos t on t.id = i.torneo_id and t.estado <> 'borrador'
  where i.estado <> 'retirado';
create view public.torneo_partidas_publicas with (security_invoker = false) as
  select p.id as partida_id, p.torneo_id, p.ronda, p.numero, p.estado, pj.inscripcion_id, i.nombre, pj.puntos, pj.gano
  from public.partidas p
  join public.torneos t on t.id = p.torneo_id and t.estado <> 'borrador'
  left join public.partida_jugadores pj on pj.partida_id = p.id
  left join public.inscripciones i on i.id = pj.inscripcion_id;
grant select on public.torneo_participantes, public.torneo_partidas_publicas to anon, authenticated;

-- Crea partidas a partir de un JSON: [{ronda, numero, estado, jugadores: [{inscripcion_id, gano?}]}]. Solo admin.
create function public.crear_partidas(p_torneo bigint, p_partidas jsonb) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.es_admin() then
    raise exception 'Solo un administrador puede crear partidas.';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_partidas) x, jsonb_array_elements(coalesce(x -> 'jugadores', '[]'::jsonb)) j
    where not exists (
      select 1 from public.inscripciones i
      where i.id = (j ->> 'inscripcion_id')::bigint and i.torneo_id = p_torneo and i.estado = 'inscrito')
  ) then
    raise exception 'Hay jugadores que no están inscritos en este torneo.';
  end if;

  with nuevas as (
    insert into public.partidas (torneo_id, ronda, numero, estado)
    select p_torneo, (x ->> 'ronda')::smallint, (x ->> 'numero')::smallint, coalesce(x ->> 'estado', 'pendiente')
    from jsonb_array_elements(p_partidas) x
    returning id, ronda, numero
  )
  insert into public.partida_jugadores (partida_id, inscripcion_id, gano)
  select n.id, (j ->> 'inscripcion_id')::bigint, (j ->> 'gano')::boolean
  from jsonb_array_elements(p_partidas) x
  join nuevas n on n.ronda = (x ->> 'ronda')::smallint and n.numero = (x ->> 'numero')::smallint
  cross join lateral jsonb_array_elements(coalesce(x -> 'jugadores', '[]'::jsonb)) j;
end;
$$;

-- Cierra las inscripciones, crea las partidas de la primera ronda y deja el torneo en curso, todo en un solo paso.
create function public.iniciar_torneo(p_torneo bigint, p_partidas jsonb) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.es_admin() then
    raise exception 'Solo un administrador puede iniciar un torneo.';
  end if;
  perform 1 from public.torneos where id = p_torneo and estado = 'inscripcion' for update;
  if not found then
    raise exception 'El torneo no está en inscripción.';
  end if;
  perform public.crear_partidas(p_torneo, p_partidas);
  update public.torneos set estado = 'en_curso', ronda_actual = 1 where id = p_torneo;
end;
$$;
revoke execute on function public.crear_partidas(bigint, jsonb), public.iniciar_torneo(bigint, jsonb) from public, anon;
grant execute on function public.crear_partidas(bigint, jsonb), public.iniciar_torneo(bigint, jsonb) to authenticated;
