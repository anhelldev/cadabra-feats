-- Torneos: el admin los crea y los conduce; el público ve los publicados y se inscribe por link.
-- Dos formatos: "puntuacion" (rondas con mesas; se anotan puntos por jugador) y "eliminacion" (llave 1 vs 1).
create table public.torneos (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nombre text not null check (char_length(btrim(nombre)) between 3 and 100),
  -- Si el juego se borra el torneo se conserva.
  juego_id bigint references public.juegos (id) on delete set null,
  descripcion text check (descripcion is null or char_length(descripcion) <= 1000),
  formato text not null check (formato in ('puntuacion', 'eliminacion')),
  fecha timestamptz not null,
  lugar text check (lugar is null or char_length(lugar) <= 120),
  cupos smallint not null check (cupos between 2 and 256),
  rondas smallint check (rondas between 1 and 20),
  tamano_mesa smallint check (tamano_mesa between 2 and 8),
  estado text not null default 'borrador' check (estado in ('borrador', 'inscripcion', 'en_curso', 'finalizado', 'cancelado')),
  ronda_actual smallint not null default 0,
  creado timestamptz not null default now(),
  constraint puntuacion_con_rondas check (formato <> 'puntuacion' or (rondas is not null and tamano_mesa is not null))
);
create index torneos_estado_idx on public.torneos (estado, fecha desc);

create table public.inscripciones (
  id bigint generated by default as identity primary key,
  torneo_id bigint not null references public.torneos (id) on delete cascade,
  nombre text not null check (char_length(btrim(nombre)) between 2 and 80),
  telefono text not null check (telefono ~ '^\+[0-9]{8,15}$'),
  email text check (email is null or (char_length(email) <= 120 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')),
  acepta boolean not null check (acepta),
  estado text not null default 'inscrito' check (estado in ('inscrito', 'espera', 'retirado')),
  creado timestamptz not null default now(),
  unique (torneo_id, telefono)
);
create index inscripciones_torneo_idx on public.inscripciones (torneo_id, estado);

-- Una partida es una mesa (puntuación) o un cruce 1 vs 1 (eliminación). En la llave, la partida (ronda, n) alimenta a
-- la (ronda + 1, ceil(n / 2)).
create table public.partidas (
  id bigint generated by default as identity primary key,
  torneo_id bigint not null references public.torneos (id) on delete cascade,
  ronda smallint not null check (ronda >= 1),
  numero smallint not null check (numero >= 1),
  estado text not null default 'pendiente' check (estado in ('pendiente', 'jugada')),
  unique (torneo_id, ronda, numero)
);
create table public.partida_jugadores (
  partida_id bigint not null references public.partidas (id) on delete cascade,
  inscripcion_id bigint not null references public.inscripciones (id) on delete cascade,
  puntos numeric,
  gano boolean,
  primary key (partida_id, inscripcion_id)
);
create index partida_jugadores_inscripcion_idx on public.partida_jugadores (inscripcion_id);

-- Lo que el visitante no decide (estado, fecha, cupo) lo fija el servidor, y se frena el abuso.
create function public.preparar_inscripcion() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  t public.torneos;
begin
  select * into t from public.torneos where id = new.torneo_id;
  if t.id is null or t.estado <> 'inscripcion' then
    raise exception 'Las inscripciones de este torneo no están abiertas.';
  end if;
  new.nombre := btrim(new.nombre);
  new.creado := now();
  new.estado := case
    when (select count(*) from public.inscripciones i where i.torneo_id = new.torneo_id and i.estado = 'inscrito') < t.cupos
    then 'inscrito' else 'espera' end;

  if (select count(*) from public.inscripciones i where i.telefono = new.telefono and i.creado > now() - interval '1 hour') >= 5 then
    raise exception 'Demasiadas inscripciones con este número. Inténtalo más tarde.';
  end if;
  if (select count(*) from public.inscripciones i where i.creado > now() - interval '1 hour') >= 300 then
    raise exception 'Hay demasiadas inscripciones ahora mismo. Inténtalo en unos minutos.';
  end if;
  return new;
end;
$$;
create trigger inscripciones_preparar before insert on public.inscripciones
  for each row execute function public.preparar_inscripcion();

